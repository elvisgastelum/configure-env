import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  formatIssuePath,
  loadSchema,
  parseSchema,
  parseSchemaText,
  type SchemaError,
} from './load.ts';

/** A schema exercising every variable type and file policy. */
const fullSchema = () => ({
  $schema:
    'https://raw.githubusercontent.com/elvisgastelum/configure-env/main/schema/env.schema.v1.json',
  version: 1,
  variables: {
    WEB_HOST: {
      type: 'host',
      description: 'Address the site is published on',
      group: 'Server',
      default: '127.0.0.1',
      required: true,
      example: '192.168.1.115',
      comment: 'Keep 127.0.0.1 behind a reverse proxy.\nSecond line.',
    },
    WEB_PORT: { type: 'port', default: 8080 },
    API_TOKEN: { type: 'string', secret: true, minLength: 20 },
    MODE: { type: 'enum', values: ['dev', 'prod'], default: 'dev' },
    WHATSAPP: {
      type: 'string',
      pattern: '^(\\d{8,15}|off)?$',
      patternMessage: 'digits or off',
    },
    RATIO: { type: 'number', min: 0, max: 1, default: 0.5 },
    WORKERS: { type: 'integer', min: 1, default: 4 },
    DEBUG: { type: 'boolean', default: false },
    CONTACT: { type: 'email', default: 'you@example.com' },
    SITE: { type: 'url', protocols: ['https'], default: 'https://example.com' },
    CADDY: { type: 'ipv4', default: '192.168.1.70', allowEmpty: false },
    CADDY_V6: { type: 'ipv6', default: 'fd00::70' },
    UPSTREAM: { type: 'ip', example: '::1' },
    APP_SUBNET: {
      type: 'cidr',
      family: 'ipv4',
      strict: true,
      default: '172.30.250.0/24',
    },
  },
  files: [
    { path: '.env.example', policy: 'merge', variables: '*' },
    {
      path: 'deploy/.env.production.example',
      policy: 'generate',
      header: 'Generated by configure-env',
      description: 'Production template',
      variables: ['WEB_HOST', 'WEB_PORT'],
      values: { WEB_HOST: '192.168.1.<CT ID>' },
    },
    { path: '.env', policy: 'create-only', mode: '600', variables: '*' },
  ],
});

type Json = ReturnType<typeof fullSchema>;

/** parseSchema on a modified copy of the full schema; returns its errors. */
function errorsFor(edit: (schema: Json & Record<string, unknown>) => void) {
  const schema = structuredClone(fullSchema()) as Json &
    Record<string, unknown>;
  edit(schema);
  const result = parseSchema(schema);
  return result.ok ? [] : result.errors;
}

const paths = (errors: SchemaError[]) => errors.map((error) => error.path);

describe('parseSchema', () => {
  it('accepts a full schema and applies the field defaults', () => {
    const result = parseSchema(fullSchema());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    const { variables, files } = result.schema;
    expect(variables.API_TOKEN).toMatchObject({
      type: 'string',
      secret: true,
      required: false,
    });
    expect(variables.WEB_HOST?.required).toBe(true);
    expect(files.map((file) => file.policy)).toEqual([
      'merge',
      'generate',
      'create-only',
    ]);
  });

  it('accepts a minimal schema', () => {
    expect(parseSchema({ version: 1, variables: {}, files: [] }).ok).toBe(true);
  });

  it('rejects a version other than 1', () => {
    const errors = errorsFor((schema) => {
      (schema as Record<string, unknown>).version = 2;
    });
    expect(paths(errors)).toEqual(['version']);
  });

  it('rejects unknown top-level keys', () => {
    const errors = errorsFor((schema) => {
      schema.varibles = {};
    });
    expect(errors).toEqual([
      { path: '(root)', message: expect.stringContaining('varibles') },
    ]);
  });

  it('rejects a typo key inside a variable', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { defualt: 80 });
    });
    expect(errors).toEqual([
      {
        path: 'variables.WEB_PORT',
        message: expect.stringContaining('defualt'),
      },
    ]);
  });

  it('rejects an option that belongs to another type', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { minLength: 2 });
    });
    expect(paths(errors)).toEqual(['variables.WEB_PORT']);
  });

  it('rejects an unknown variable type', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { type: 'float' });
    });
    expect(errors).toEqual([
      {
        path: 'variables.WEB_PORT.type',
        message: expect.stringContaining('string, number'),
      },
    ]);
  });

  it('rejects an invalid variable name', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables, { 'BAD-NAME': { type: 'string' } });
    });
    expect(errors).toEqual([
      {
        path: 'variables["BAD-NAME"]',
        message: expect.stringContaining('variable names'),
      },
    ]);
  });

  describe('defaults and examples', () => {
    it.each([
      ['host', { type: 'host', default: 'bad host' }],
      ['port out of range', { type: 'port', default: 70000 }],
      ['port as a string', { type: 'port', default: '8080' }],
      ['integer with a fraction', { type: 'integer', default: 1.5 }],
      ['number below min', { type: 'number', min: 1, default: 0 }],
      ['number above max', { type: 'number', max: 1, default: 2 }],
      ['boolean as a string', { type: 'boolean', default: 'true' }],
      ['enum value not listed', { type: 'enum', values: ['a'], default: 'b' }],
      ['email', { type: 'email', default: 'nope' }],
      [
        'url protocol',
        { type: 'url', protocols: ['https'], default: 'http://x.io' },
      ],
      ['ipv4', { type: 'ipv4', default: '300.1.1.1' }],
      ['ipv6', { type: 'ipv6', default: '10.0.0.1' }],
      ['ip', { type: 'ip', default: '1::2::3' }],
      ['cidr without a prefix', { type: 'cidr', default: '10.0.0.0' }],
      [
        'cidr of the other family',
        { type: 'cidr', family: 'ipv6', default: '10.0.0.0/8' },
      ],
      [
        'cidr with host bits',
        { type: 'cidr', strict: true, default: '10.0.0.1/8' },
      ],
      ['string too short', { type: 'string', minLength: 3, default: 'ab' }],
      ['string too long', { type: 'string', maxLength: 1, default: 'ab' }],
      ['string pattern', { type: 'string', pattern: '^a+$', default: 'b' }],
      [
        'string encoding',
        { type: 'string', encoding: 'base64', bytes: 4, default: 'AAAA' },
      ],
      [
        'empty when not allowed',
        { type: 'string', required: true, default: '' },
      ],
    ])('rejects an invalid default: %s', (_label, spec) => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: spec });
      });
      expect(paths(errors)).toEqual([
        expect.stringMatching(/^variables\.X(\.default)?$/),
      ]);
    });

    it('accepts encoded values whose length fits minLength and maxLength', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, {
          X: {
            type: 'string',
            encoding: 'base64',
            bytes: 3,
            minLength: 4,
            maxLength: 4,
            default: 'AAAA',
            example: 'AQID',
          },
        });
      });
      expect(errors).toEqual([]);
    });

    it('rejects an example that is not in the encoding', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, {
          X: { type: 'string', encoding: 'hex', example: 'xyz' },
        });
      });
      expect(errors).toEqual([
        {
          path: 'variables.X.example',
          message: 'invalid example: must be hex',
        },
      ]);
    });

    it('rejects an invalid example', () => {
      const errors = errorsFor((schema) => {
        schema.variables.WEB_HOST.example = 'not a host!';
      });
      expect(paths(errors)).toEqual(['variables.WEB_HOST.example']);
    });

    it('reports the type rule in the default error', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: { type: 'port', default: 0 } });
      });
      expect(errors[0]?.message).toMatch(/65535/);
    });
  });

  describe('type options', () => {
    it.each([
      ['an invalid pattern', { type: 'string', pattern: '(' }, 'pattern'],
      [
        'minLength above maxLength',
        { type: 'string', minLength: 3, maxLength: 2 },
        'minLength',
      ],
      ['min above max', { type: 'number', min: 3, max: 2 }, 'min'],
      ['an empty enum', { type: 'enum', values: [] }, 'values'],
      ['a repeated enum value', { type: 'enum', values: ['a', 'a'] }, 'values'],
      ['an empty protocol list', { type: 'url', protocols: [] }, 'protocols'],
      ['bytes without encoding', { type: 'string', bytes: 32 }, 'bytes'],
      ['zero bytes', { type: 'string', encoding: 'hex', bytes: 0 }, 'bytes'],
      [
        'an unknown encoding',
        { type: 'string', encoding: 'base32' },
        'encoding',
      ],
      [
        'a minLength above the encoded length',
        { type: 'string', encoding: 'base64', bytes: 32, minLength: 45 },
        'minLength',
      ],
      [
        'a maxLength below the encoded length',
        { type: 'string', encoding: 'hex', bytes: 16, maxLength: 31 },
        'maxLength',
      ],
      ['an unknown cidr family', { type: 'cidr', family: 'ipv5' }, 'family'],
      [
        'a strict that is not a boolean',
        { type: 'cidr', strict: 'yes' },
        'strict',
      ],
    ])('rejects %s', (_label, spec, field) => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: spec });
      });
      expect(paths(errors)).toEqual([`variables.X.${field}`]);
    });
  });

  it.each([
    ['family', 'ipv4', { family: 'ipv4' }],
    ['family', 'ip', { family: 'any' }],
    ['strict', 'ipv6', { strict: true }],
    ['strict', 'string', { strict: false }],
  ])('rejects %s on a %s variable', (_field, type, option) => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables, { X: { type, ...option } });
    });
    expect(paths(errors)).toEqual(['variables.X']);
  });

  describe('rules between variables', () => {
    const withX = (x: Record<string, unknown>) =>
      errorsFor((schema) => {
        Object.assign(schema.variables, { X: { type: 'string', ...x } });
      });

    it('accepts a name or a list of declared names', () => {
      expect(
        withX({
          requiredUnless: 'WEB_HOST',
          conflictsWith: ['WEB_HOST', 'WEB_PORT'],
          distinctFrom: 'API_TOKEN',
        }),
      ).toEqual([]);
    });

    it.each(['requiredUnless', 'conflictsWith', 'distinctFrom'])(
      'rejects an undeclared name, the variable itself and an empty list in %s',
      (field) => {
        expect(withX({ [field]: 'NOPE' })).toEqual([
          {
            path: `variables.X.${field}`,
            message: 'NOPE is not declared in variables',
          },
        ]);
        expect(withX({ [field]: ['WEB_HOST', 'X'] })).toEqual([
          {
            path: `variables.X.${field}[1]`,
            message: 'must not name the variable itself',
          },
        ]);
        expect(paths(withX({ [field]: [] }))).toEqual([`variables.X.${field}`]);
        expect(paths(withX({ [field]: 'not a name' }))).toEqual([
          `variables.X.${field}`,
        ]);
      },
    );

    it('rejects requiredUnless together with required: true', () => {
      expect(withX({ required: true, requiredUnless: 'WEB_HOST' })).toEqual([
        {
          path: 'variables.X.requiredUnless',
          message: 'requiredUnless cannot be combined with required: true',
        },
      ]);
    });
  });

  describe('within', () => {
    /** A schema with APP_SUBNET and WEB_ADDRESS, edited by `edit`. */
    const network = (
      web: Record<string, unknown>,
      subnet: Record<string, unknown> = {},
      files: unknown[] = [],
    ) => {
      const result = parseSchema({
        version: 1,
        variables: {
          APP_SUBNET: {
            type: 'cidr',
            family: 'ipv4',
            default: '172.30.250.0/24',
            ...subnet,
          },
          WEB_ADDRESS: { type: 'ipv4', within: 'APP_SUBNET', ...web },
          NAME: { type: 'string' },
        },
        files,
      });
      return result.ok ? [] : result.errors;
    };

    it('accepts a default and example inside the target default', () => {
      expect(
        network({ default: '172.30.250.10', example: '172.30.250.20' }),
      ).toEqual([]);
      expect(network({ type: 'ip', default: '172.30.250.10' })).toEqual([]);
      expect(network({ type: 'cidr', default: '172.30.250.128/25' })).toEqual(
        [],
      );
    });

    it('rejects a default or example outside the target default, naming both keys and no value', () => {
      const errors = network({
        default: '172.30.251.10',
        example: '10.0.0.1',
      });
      expect(errors).toEqual([
        {
          path: 'variables.WEB_ADDRESS.default',
          message:
            'invalid default: WEB_ADDRESS must be within the default of APP_SUBNET',
        },
        {
          path: 'variables.WEB_ADDRESS.example',
          message:
            'invalid example: WEB_ADDRESS must be within the default of APP_SUBNET',
        },
      ]);
      expect(JSON.stringify(errors)).not.toMatch(/172\.30|10\.0/);
      expect(
        paths(network({ type: 'cidr', default: '172.30.0.0/16' })),
      ).toEqual(['variables.WEB_ADDRESS.default']);
    });

    it('skips the check without a target default or with an invalid value', () => {
      expect(network({ default: '10.0.0.1' }, { default: undefined })).toEqual(
        [],
      );
      expect(paths(network({ default: '300.0.0.1' }))).toEqual([
        'variables.WEB_ADDRESS.default',
      ]);
      expect(
        paths(network({ default: '10.0.0.1' }, { default: '172.30.250.0' })),
      ).toEqual(['variables.APP_SUBNET.default']);
    });

    it.each([
      [
        'an undeclared target',
        { within: 'NOPE' },
        'NOPE is not declared in variables',
      ],
      [
        'the variable itself',
        { within: 'WEB_ADDRESS' },
        'must not name the variable itself',
      ],
      [
        'a target that is not cidr',
        { within: 'NAME' },
        'NAME is not a cidr variable',
      ],
      [
        'a target of the other family',
        { type: 'ipv6' },
        'APP_SUBNET holds ipv4 blocks only, so WEB_ADDRESS can never be within it',
      ],
      [
        'a cidr target of the other family',
        { type: 'cidr', family: 'ipv6' },
        'APP_SUBNET holds ipv4 blocks only, so WEB_ADDRESS can never be within it',
      ],
    ])('rejects %s', (_label, web, message) => {
      expect(network(web)).toEqual([
        { path: 'variables.WEB_ADDRESS.within', message },
      ]);
    });

    it.each(['string', 'host', 'port'])('is not an option of %s', (type) => {
      expect(paths(network({ type, default: undefined }, {}, []))).toEqual([
        'variables.WEB_ADDRESS',
      ]);
    });

    it('rejects a list of names', () => {
      expect(paths(network({ within: ['APP_SUBNET'] }))).toEqual([
        'variables.WEB_ADDRESS.within',
      ]);
    });

    describe('template values', () => {
      const template = (values: Record<string, string>, extra = {}) =>
        network({}, {}, [
          {
            path: '.env.example',
            policy: 'generate',
            variables: '*',
            values,
            ...extra,
          },
        ]);

      it('checks the values a template writes, with the defaults', () => {
        expect(template({ WEB_ADDRESS: '172.30.250.10' })).toEqual([]);
        const errors = template({ WEB_ADDRESS: '172.30.251.10' });
        expect(errors).toEqual([
          {
            path: 'files[0].values.WEB_ADDRESS',
            message: 'WEB_ADDRESS must be within APP_SUBNET',
          },
        ]);
        expect(JSON.stringify(errors)).not.toContain('172.30');
        expect(
          paths(
            template({ APP_SUBNET: '10.0.0.0/8', WEB_ADDRESS: '172.30.250.9' }),
          ),
        ).toEqual(['files[0].values.WEB_ADDRESS']);
        expect(paths(template({ APP_SUBNET: '10.0.0.0/8' }))).toEqual([]);
      });

      it('reports under the target when only its value is given', () => {
        const errors = network({ default: '172.30.250.10' }, {}, [
          {
            path: '.env.example',
            policy: 'generate',
            variables: '*',
            values: { APP_SUBNET: '10.0.0.0/8' },
          },
        ]);
        expect(errors).toEqual([
          {
            path: 'files[0].values.APP_SUBNET',
            message: 'WEB_ADDRESS must be within APP_SUBNET',
          },
        ]);
      });

      it('skips placeholders, files that are not templates and files without both keys', () => {
        expect(template({ WEB_ADDRESS: '<web address>' })).toEqual([]);
        expect(template({ WEB_ADDRESS: '10.0.0.1' }, { path: '.env' })).toEqual(
          [],
        );
        expect(
          template({ WEB_ADDRESS: '10.0.0.1' }, { variables: ['WEB_ADDRESS'] }),
        ).toEqual([]);
      });
    });
  });

  describe('protected', () => {
    const withX = (x: Record<string, unknown>) =>
      errorsFor((schema) => {
        Object.assign(schema.variables, { X: { type: 'string', ...x } });
      });

    it('accepts true or a reason on a secret', () => {
      expect(withX({ secret: true, protected: true })).toEqual([]);
      expect(
        withX({ secret: true, protected: { reason: 'encrypts the vault' } }),
      ).toEqual([]);
    });

    it('needs secret: true', () => {
      expect(withX({ protected: true })).toEqual([
        {
          path: 'variables.X.protected',
          message: 'protected needs secret: true',
        },
      ]);
    });

    it.each([
      ['false', false],
      ['an empty reason', { reason: '' }],
      ['an unknown field', { reason: 'r', why: 'r' }],
      ['a bare string', 'encrypts the vault'],
    ])('rejects %s', (_label, value) => {
      expect(paths(withX({ secret: true, protected: value }))).toEqual([
        expect.stringMatching(/^variables\.X\.protected/),
      ]);
    });
  });

  describe('files', () => {
    it('rejects a file variable that is not declared', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.variables = ['WEB_HOST', 'NOPE'];
      });
      expect(errors).toEqual([
        {
          path: 'files[1].variables[1]',
          message: expect.stringContaining('NOPE'),
        },
      ]);
    });

    it('rejects a variable listed twice in a file', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.variables = ['WEB_HOST', 'WEB_HOST'];
      });
      expect(paths(errors)).toEqual(['files[1].variables[1]']);
    });

    it('rejects a value override for a variable the file does not hold', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.values = { MODE: 'x' } as never;
      });
      expect(paths(errors)).toEqual(['files[1].values.MODE']);
    });

    it('accepts value overrides that would fail the type, as placeholders', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.values = { WEB_PORT: '<port>' } as never;
      });
      expect(errors).toEqual([]);
    });

    it('accepts per-file comment overrides', () => {
      const errors = errorsFor((schema) => {
        (schema.files[1] as Record<string, unknown>).comments = {
          WEB_HOST: 'For production.\nSecond line.',
        };
      });
      expect(errors).toEqual([]);
    });

    it('rejects a comment override for a variable the file does not hold', () => {
      const errors = errorsFor((schema) => {
        (schema.files[1] as Record<string, unknown>).comments = {
          MODE: 'x',
          NOPE: 'y',
        };
      });
      expect(paths(errors)).toEqual([
        'files[1].comments.MODE',
        'files[1].comments.NOPE',
      ]);
    });

    it('rejects a value override with a line break', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.values = { WEB_HOST: 'a\nB=1' } as never;
      });
      expect(paths(errors)).toEqual(['files[1].values.WEB_HOST']);
    });

    it('rejects a duplicate path', () => {
      const errors = errorsFor((schema) => {
        schema.files[2]!.path = '.env.example';
      });
      expect(errors).toEqual([
        { path: 'files[2].path', message: expect.stringContaining('files[0]') },
      ]);
    });

    it.each([
      ['an absolute path', '/etc/app.env'],
      ['a parent segment', '../app.env'],
      ['an inner parent segment', 'deploy/../../app.env'],
      ['a current-directory segment', './app.env'],
      ['an empty segment', 'deploy//app.env'],
      ['a trailing slash', 'deploy/'],
      ['a backslash', 'deploy\\app.env'],
      ['a drive letter', 'C:/app.env'],
      ['a NUL byte', 'app\u0000.env'],
      ['an empty path', ''],
    ])('rejects %s', (_label, path) => {
      const errors = errorsFor((schema) => {
        schema.files[0]!.path = path;
      });
      expect(paths(errors)).toEqual(['files[0].path']);
    });

    it.each(['60', '6000', '800', 'rw', 600])('rejects the mode %j', (mode) => {
      const errors = errorsFor((schema) => {
        (schema.files[2] as Record<string, unknown>).mode = mode;
      });
      expect(paths(errors)).toEqual(['files[2].mode']);
    });

    it('rejects an unknown policy', () => {
      const errors = errorsFor((schema) => {
        (schema.files[0] as Record<string, unknown>).policy = 'overwrite';
      });
      expect(paths(errors)).toEqual(['files[0].policy']);
    });

    it('rejects a typo key in a file', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.files[0]!, { polcy: 'merge' });
      });
      expect(errors).toEqual([
        { path: 'files[0]', message: expect.stringContaining('polcy') },
      ]);
    });
  });
});

describe('formatIssuePath', () => {
  it.each([
    [[], '(root)'],
    [['version'], 'version'],
    [['files', 1, 'variables', 0], 'files[1].variables[0]'],
    [['variables', 'WEB_HOST', 'default'], 'variables.WEB_HOST.default'],
    [['variables', 'BAD-NAME'], 'variables["BAD-NAME"]'],
    [['variables', '1X'], 'variables["1X"]'],
  ])('formats %j as %s', (path, expected) => {
    expect(formatIssuePath(path)).toBe(expected);
  });
});

describe('parseSchemaText', () => {
  it('parses and validates JSON text', () => {
    const result = parseSchemaText(JSON.stringify(fullSchema()));
    expect(result.ok).toBe(true);
  });

  it('tolerates a UTF-8 byte order mark', () => {
    const result = parseSchemaText(`\uFEFF${JSON.stringify(fullSchema())}`);
    expect(result.ok).toBe(true);
  });

  it('reports the line and column of a syntax error', () => {
    const text = '{\n  "version": 1,\n  "variables": {,\n}';
    const result = parseSchemaText(text);
    expect(result).toEqual({
      ok: false,
      errors: [
        {
          path: '(root)',
          line: 3,
          column: 17,
          message: expect.stringMatching(/^invalid JSON at line 3, column 17/),
        },
      ],
    });
  });

  it('reports the end of the text for truncated JSON', () => {
    const result = parseSchemaText('{\n  "version": 1');
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.errors[0]).toMatchObject({ line: 2, column: 15 });
  });
});

describe('loadSchema', () => {
  let dir: string;

  beforeAll(async () => {
    dir = await mkdtemp(join(tmpdir(), 'configure-env-schema-'));
  });

  afterAll(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('loads a schema file', async () => {
    const file = join(dir, 'env.schema.json');
    await writeFile(file, JSON.stringify(fullSchema()));
    const result = await loadSchema(file);
    expect(result.ok).toBe(true);
  });

  it('reports a schema error', async () => {
    const file = join(dir, 'bad.schema.json');
    await writeFile(file, JSON.stringify({ version: 1, variables: {} }));
    const result = await loadSchema(file);
    expect(result).toEqual({
      ok: false,
      errors: [{ path: 'files', message: expect.any(String) }],
    });
  });

  it('reports a file it cannot read', async () => {
    const result = await loadSchema(join(dir, 'missing.schema.json'));
    expect(result).toEqual({
      ok: false,
      errors: [
        { path: '(root)', message: expect.stringContaining('cannot read') },
      ],
    });
  });
});
