// Parity with the legacy portfolio templates: the engine, driven by
// examples/portfolio.env.schema.json, writes what the retired hand-written
// templates (and the bash script before them) wrote.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { describe, expect, it } from 'vite-plus/test';
import { loadSchema } from '../schema/load.ts';
import { validateValue } from '../schema/values.ts';
import { planChanges } from './plan.ts';
import { useTempRoot } from './test-helpers.ts';

const temp = useTempRoot();

// The example lives with the CLI, which documents it.
const SCHEMA_PATH = fileURLToPath(
  new URL('../../../cli/examples/portfolio.env.schema.json', import.meta.url),
);
const PRODUCTION = 'deploy/.env.production.example';
const EXAMPLE = '.env.example';
const LOCAL = '.env';

// The heredoc of the retired scripts/configure-env.sh, byte for byte.
const bashOutput = readFile(
  new URL('../fixtures/bash-production-template.txt', import.meta.url),
  'utf8',
);

// What the retired renderExampleBlock wrote for .env.example and .env.
const LEGACY_EXAMPLE = [
  '# Address the web container is published on; keep 127.0.0.1 behind a reverse proxy on the same host.',
  'WEB_HOST=127.0.0.1',
  '',
  '# Host port the site is published on.',
  'WEB_PORT=8080',
  '',
  '# Contact details embedded in the bundle at build time (README, "Contact variables").',
  '# Empty keeps the defaults in apps/web/src/config/site.ts; VITE_CONTACT_WHATSAPP=off hides WhatsApp.',
  'VITE_CONTACT_EMAIL=',
  'VITE_CONTACT_WHATSAPP=',
  '',
].join('\n');

async function portfolio() {
  const result = await loadSchema(SCHEMA_PATH);
  if (!result.ok) throw new Error(JSON.stringify(result.errors));
  return result.schema;
}

const plan = async (values: Record<string, string> = {}) =>
  Object.fromEntries(
    (
      await planChanges({
        schema: await portfolio(),
        root: temp.dirs.root,
        values,
      })
    ).files.map((file) => [file.path, file]),
  );

describe('the portfolio schema', () => {
  it('generates the production example as the bash template did', async () => {
    const bash = await bashOutput;
    // The one intended difference: the header names the schema, not the
    // retired script, as the place to edit.
    const expected = bash.replace(
      '# Generated by `pnpm configure:env`: edit the template in\n' +
        '# scripts/configure-env.sh, not this file, which the script rewrites.\n',
      '# Generated by configure-env from env.schema.json: edit the schema, not this\n' +
        '# file, which the tool rewrites.\n',
    );
    expect(expected).not.toBe(bash);
    const files = await plan();
    expect(files[PRODUCTION]).toMatchObject({ action: 'create' });
    expect(files[PRODUCTION]!.content).toBe(expected);
  });

  it('creates .env.example as the legacy template did', async () => {
    expect((await plan())[EXAMPLE]!.content).toBe(LEGACY_EXAMPLE);
  });

  it('creates .env from the values, as the legacy template did', async () => {
    const files = await plan({
      WEB_PORT: '9000',
      VITE_CONTACT_WHATSAPP: 'off',
    });
    expect(files[LOCAL]).toMatchObject({ action: 'create', mode: 0o600 });
    expect(files[LOCAL]!.content).toBe(
      LEGACY_EXAMPLE.replace('WEB_PORT=8080', 'WEB_PORT=9000').replace(
        'VITE_CONTACT_WHATSAPP=\n',
        'VITE_CONTACT_WHATSAPP=off\n',
      ),
    );
  });

  it('appends the missing .env.example keys after the existing lines', async () => {
    await writeFile(
      join(temp.dirs.root, EXAMPLE),
      'CUSTOM=1\nWEB_HOST=10.0.0.5\n',
    );
    const file = (await plan())[EXAMPLE]!;
    expect(file.addedKeys).toEqual([
      'WEB_PORT',
      'VITE_CONTACT_EMAIL',
      'VITE_CONTACT_WHATSAPP',
    ]);
    expect(file.content).toBe(
      'CUSTOM=1\nWEB_HOST=10.0.0.5\n\n' +
        LEGACY_EXAMPLE.slice(LEGACY_EXAMPLE.indexOf('# Host port')),
    );
  });
});

// The value rules of the retired src/schema.ts, now in the schema.
describe('the portfolio schema value rules', () => {
  it.each([
    ['WEB_HOST', '192.168.1.70'],
    ['WEB_HOST', 'web.internal'],
    ['WEB_HOST', 'localhost'],
    ['WEB_PORT', '1'],
    ['WEB_PORT', '65535'],
    ['VITE_CONTACT_EMAIL', ''],
    ['VITE_CONTACT_EMAIL', 'you@example.com'],
    ['VITE_CONTACT_WHATSAPP', ''],
    ['VITE_CONTACT_WHATSAPP', '5215555555555'],
    ['VITE_CONTACT_WHATSAPP', 'off'],
  ])('accepts %s=%j', async (key, value) => {
    const spec = (await portfolio()).variables[key]!;
    expect(validateValue(spec, value).ok).toBe(true);
  });

  it.each([
    ['WEB_HOST', ''],
    ['WEB_HOST', 'bad host'],
    ['WEB_HOST', '-leading.dash'],
    ['WEB_PORT', '0'],
    ['WEB_PORT', '65536'],
    ['WEB_PORT', '80a'],
    ['VITE_CONTACT_EMAIL', 'not-an-email'],
    ['VITE_CONTACT_WHATSAPP', '+52 638'],
    ['VITE_CONTACT_WHATSAPP', 'on'],
  ])('rejects %s=%j', async (key, value) => {
    const spec = (await portfolio()).variables[key]!;
    expect(validateValue(spec, value).ok).toBe(false);
  });
});
