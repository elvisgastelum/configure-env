import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  formatIssuePath,
  loadSchema,
  parseSchema,
  parseSchemaText,
  type SchemaError,
} from './load.ts';

/** A schema exercising every variable type and file policy. */
const fullSchema = () => ({
  $schema:
    'https://raw.githubusercontent.com/elvisgastelum/configure-env/main/schema/env.schema.v1.json',
  version: 1,
  variables: {
    WEB_HOST: {
      type: 'host',
      description: 'Address the site is published on',
      group: 'Server',
      default: '127.0.0.1',
      required: true,
      example: '192.168.1.115',
      comment: 'Keep 127.0.0.1 behind a reverse proxy.\nSecond line.',
    },
    WEB_PORT: { type: 'port', default: 8080 },
    API_TOKEN: { type: 'string', secret: true, minLength: 20 },
    MODE: { type: 'enum', values: ['dev', 'prod'], default: 'dev' },
    WHATSAPP: {
      type: 'string',
      pattern: '^(\\d{8,15}|off)?$',
      patternMessage: 'digits or off',
    },
    RATIO: { type: 'number', min: 0, max: 1, default: 0.5 },
    WORKERS: { type: 'integer', min: 1, default: 4 },
    DEBUG: { type: 'boolean', default: false },
    CONTACT: { type: 'email', default: 'you@example.com' },
    SITE: { type: 'url', protocols: ['https'], default: 'https://example.com' },
    CADDY: { type: 'ipv4', default: '192.168.1.70', allowEmpty: false },
  },
  files: [
    { path: '.env.example', policy: 'merge', variables: '*' },
    {
      path: 'deploy/.env.production.example',
      policy: 'generate',
      header: 'Generated by configure-env',
      description: 'Production template',
      variables: ['WEB_HOST', 'WEB_PORT'],
      values: { WEB_HOST: '192.168.1.<CT ID>' },
    },
    { path: '.env', policy: 'create-only', mode: '600', variables: '*' },
  ],
});

type Json = ReturnType<typeof fullSchema>;

/** parseSchema on a modified copy of the full schema; returns its errors. */
function errorsFor(edit: (schema: Json & Record<string, unknown>) => void) {
  const schema = structuredClone(fullSchema()) as Json &
    Record<string, unknown>;
  edit(schema);
  const result = parseSchema(schema);
  return result.ok ? [] : result.errors;
}

const paths = (errors: SchemaError[]) => errors.map((error) => error.path);

describe('parseSchema', () => {
  it('accepts a full schema and applies the field defaults', () => {
    const result = parseSchema(fullSchema());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    const { variables, files } = result.schema;
    expect(variables.API_TOKEN).toMatchObject({
      type: 'string',
      secret: true,
      required: false,
    });
    expect(variables.WEB_HOST?.required).toBe(true);
    expect(files.map((file) => file.policy)).toEqual([
      'merge',
      'generate',
      'create-only',
    ]);
  });

  it('accepts a minimal schema', () => {
    expect(parseSchema({ version: 1, variables: {}, files: [] }).ok).toBe(true);
  });

  it('rejects a version other than 1', () => {
    const errors = errorsFor((schema) => {
      (schema as Record<string, unknown>).version = 2;
    });
    expect(paths(errors)).toEqual(['version']);
  });

  it('rejects unknown top-level keys', () => {
    const errors = errorsFor((schema) => {
      schema.varibles = {};
    });
    expect(errors).toEqual([
      { path: '(root)', message: expect.stringContaining('varibles') },
    ]);
  });

  it('rejects a typo key inside a variable', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { defualt: 80 });
    });
    expect(errors).toEqual([
      {
        path: 'variables.WEB_PORT',
        message: expect.stringContaining('defualt'),
      },
    ]);
  });

  it('rejects an option that belongs to another type', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { minLength: 2 });
    });
    expect(paths(errors)).toEqual(['variables.WEB_PORT']);
  });

  it('rejects an unknown variable type', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables.WEB_PORT, { type: 'float' });
    });
    expect(errors).toEqual([
      {
        path: 'variables.WEB_PORT.type',
        message: expect.stringContaining('string, number'),
      },
    ]);
  });

  it('rejects an invalid variable name', () => {
    const errors = errorsFor((schema) => {
      Object.assign(schema.variables, { 'BAD-NAME': { type: 'string' } });
    });
    expect(errors).toEqual([
      {
        path: 'variables["BAD-NAME"]',
        message: expect.stringContaining('variable names'),
      },
    ]);
  });

  describe('defaults and examples', () => {
    it.each([
      ['host', { type: 'host', default: 'bad host' }],
      ['port out of range', { type: 'port', default: 70000 }],
      ['port as a string', { type: 'port', default: '8080' }],
      ['integer with a fraction', { type: 'integer', default: 1.5 }],
      ['number below min', { type: 'number', min: 1, default: 0 }],
      ['number above max', { type: 'number', max: 1, default: 2 }],
      ['boolean as a string', { type: 'boolean', default: 'true' }],
      ['enum value not listed', { type: 'enum', values: ['a'], default: 'b' }],
      ['email', { type: 'email', default: 'nope' }],
      [
        'url protocol',
        { type: 'url', protocols: ['https'], default: 'http://x.io' },
      ],
      ['ipv4', { type: 'ipv4', default: '300.1.1.1' }],
      ['string too short', { type: 'string', minLength: 3, default: 'ab' }],
      ['string too long', { type: 'string', maxLength: 1, default: 'ab' }],
      ['string pattern', { type: 'string', pattern: '^a+$', default: 'b' }],
      [
        'empty when not allowed',
        { type: 'string', required: true, default: '' },
      ],
    ])('rejects an invalid default: %s', (_label, spec) => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: spec });
      });
      expect(paths(errors)).toEqual([
        expect.stringMatching(/^variables\.X(\.default)?$/),
      ]);
    });

    it('rejects an invalid example', () => {
      const errors = errorsFor((schema) => {
        schema.variables.WEB_HOST.example = 'not a host!';
      });
      expect(paths(errors)).toEqual(['variables.WEB_HOST.example']);
    });

    it('reports the type rule in the default error', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: { type: 'port', default: 0 } });
      });
      expect(errors[0]?.message).toMatch(/65535/);
    });
  });

  describe('type options', () => {
    it.each([
      ['an invalid pattern', { type: 'string', pattern: '(' }, 'pattern'],
      [
        'minLength above maxLength',
        { type: 'string', minLength: 3, maxLength: 2 },
        'minLength',
      ],
      ['min above max', { type: 'number', min: 3, max: 2 }, 'min'],
      ['an empty enum', { type: 'enum', values: [] }, 'values'],
      ['a repeated enum value', { type: 'enum', values: ['a', 'a'] }, 'values'],
      ['an empty protocol list', { type: 'url', protocols: [] }, 'protocols'],
    ])('rejects %s', (_label, spec, field) => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.variables, { X: spec });
      });
      expect(paths(errors)).toEqual([`variables.X.${field}`]);
    });
  });

  describe('files', () => {
    it('rejects a file variable that is not declared', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.variables = ['WEB_HOST', 'NOPE'];
      });
      expect(errors).toEqual([
        {
          path: 'files[1].variables[1]',
          message: expect.stringContaining('NOPE'),
        },
      ]);
    });

    it('rejects a variable listed twice in a file', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.variables = ['WEB_HOST', 'WEB_HOST'];
      });
      expect(paths(errors)).toEqual(['files[1].variables[1]']);
    });

    it('rejects a value override for a variable the file does not hold', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.values = { MODE: 'x' } as never;
      });
      expect(paths(errors)).toEqual(['files[1].values.MODE']);
    });

    it('accepts value overrides that would fail the type, as placeholders', () => {
      const errors = errorsFor((schema) => {
        schema.files[1]!.values = { WEB_PORT: '<port>' } as never;
      });
      expect(errors).toEqual([]);
    });

    it('rejects a duplicate path', () => {
      const errors = errorsFor((schema) => {
        schema.files[2]!.path = '.env.example';
      });
      expect(errors).toEqual([
        { path: 'files[2].path', message: expect.stringContaining('files[0]') },
      ]);
    });

    it.each([
      ['an absolute path', '/etc/app.env'],
      ['a parent segment', '../app.env'],
      ['an inner parent segment', 'deploy/../../app.env'],
      ['a current-directory segment', './app.env'],
      ['an empty segment', 'deploy//app.env'],
      ['a trailing slash', 'deploy/'],
      ['a backslash', 'deploy\\app.env'],
      ['a drive letter', 'C:/app.env'],
      ['a NUL byte', 'app\u0000.env'],
      ['an empty path', ''],
    ])('rejects %s', (_label, path) => {
      const errors = errorsFor((schema) => {
        schema.files[0]!.path = path;
      });
      expect(paths(errors)).toEqual(['files[0].path']);
    });

    it.each(['60', '6000', '800', 'rw', 600])('rejects the mode %j', (mode) => {
      const errors = errorsFor((schema) => {
        (schema.files[2] as Record<string, unknown>).mode = mode;
      });
      expect(paths(errors)).toEqual(['files[2].mode']);
    });

    it('rejects an unknown policy', () => {
      const errors = errorsFor((schema) => {
        (schema.files[0] as Record<string, unknown>).policy = 'overwrite';
      });
      expect(paths(errors)).toEqual(['files[0].policy']);
    });

    it('rejects a typo key in a file', () => {
      const errors = errorsFor((schema) => {
        Object.assign(schema.files[0]!, { polcy: 'merge' });
      });
      expect(errors).toEqual([
        { path: 'files[0]', message: expect.stringContaining('polcy') },
      ]);
    });
  });
});

describe('formatIssuePath', () => {
  it.each([
    [[], '(root)'],
    [['version'], 'version'],
    [['files', 1, 'variables', 0], 'files[1].variables[0]'],
    [['variables', 'WEB_HOST', 'default'], 'variables.WEB_HOST.default'],
    [['variables', 'BAD-NAME'], 'variables["BAD-NAME"]'],
    [['variables', '1X'], 'variables["1X"]'],
  ])('formats %j as %s', (path, expected) => {
    expect(formatIssuePath(path)).toBe(expected);
  });
});

describe('parseSchemaText', () => {
  it('parses and validates JSON text', () => {
    const result = parseSchemaText(JSON.stringify(fullSchema()));
    expect(result.ok).toBe(true);
  });

  it('reports the line and column of a syntax error', () => {
    const text = '{\n  "version": 1,\n  "variables": {,\n}';
    const result = parseSchemaText(text);
    expect(result).toEqual({
      ok: false,
      errors: [
        {
          path: '(root)',
          line: 3,
          column: 17,
          message: expect.stringMatching(/^invalid JSON at line 3, column 17/),
        },
      ],
    });
  });

  it('reports the end of the text for truncated JSON', () => {
    const result = parseSchemaText('{\n  "version": 1');
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.errors[0]).toMatchObject({ line: 2, column: 15 });
  });
});

describe('loadSchema', () => {
  let dir: string;

  beforeAll(async () => {
    dir = await mkdtemp(join(tmpdir(), 'configure-env-schema-'));
  });

  afterAll(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('loads a schema file', async () => {
    const file = join(dir, 'env.schema.json');
    await writeFile(file, JSON.stringify(fullSchema()));
    const result = await loadSchema(file);
    expect(result.ok).toBe(true);
  });

  it('reports a schema error', async () => {
    const file = join(dir, 'bad.schema.json');
    await writeFile(file, JSON.stringify({ version: 1, variables: {} }));
    const result = await loadSchema(file);
    expect(result).toEqual({
      ok: false,
      errors: [{ path: 'files', message: expect.any(String) }],
    });
  });

  it('reports a file it cannot read', async () => {
    const result = await loadSchema(join(dir, 'missing.schema.json'));
    expect(result).toEqual({
      ok: false,
      errors: [
        { path: '(root)', message: expect.stringContaining('cannot read') },
      ],
    });
  });
});
